"use client";

import { useEffect, useState } from "react";
import { useRouter } from "next/navigation";
import { Field, Input } from "@/components/ui/form";
import { Button } from "@/components/ui/button";
import { Alert } from "@/components/ui/alert";
import { createClient } from "@/lib/supabase/client";

type Mode = { kind: "loading" } | { kind: "enroll"; factorId: string; qr: string; secret: string } | { kind: "verify"; factorId: string };

/** Admin two-factor (TOTP): first sign-in enrols an authenticator app, later sign-ins verify a code. */
export function MfaForm({ next }: { next: string }) {
  const router = useRouter();
  const [mode, setMode] = useState<Mode>({ kind: "loading" });
  const [code, setCode] = useState("");
  const [error, setError] = useState<string | null>(null);
  const [busy, setBusy] = useState(false);

  useEffect(() => {
    let cancelled = false;
    (async () => {
      const supabase = createClient();
      const { data: factors, error: listError } = await supabase.auth.mfa.listFactors();
      if (cancelled) return;
      if (listError) return setError("Could not start two-factor sign-in. Refresh and try again.");

      const verified = factors?.totp?.find((f) => f.status === "verified");
      if (verified) return setMode({ kind: "verify", factorId: verified.id });

      // Remove half-finished enrolments, then start a new one.
      for (const f of factors?.all ?? []) if (f.status === "unverified") await supabase.auth.mfa.unenroll({ factorId: f.id });
      const { data, error: enrollError } = await supabase.auth.mfa.enroll({ factorType: "totp", friendlyName: "Authenticator app" });
      if (cancelled) return;
      if (enrollError || !data) return setError("Could not start two-factor setup. Refresh and try again.");
      setMode({ kind: "enroll", factorId: data.id, qr: data.totp.qr_code, secret: data.totp.secret });
    })();
    return () => {
      cancelled = true;
    };
  }, []);

  async function submit(e: React.FormEvent) {
    e.preventDefault();
    if (mode.kind === "loading") return;
    if (!/^\d{6}$/.test(code.trim())) return setError("Enter the 6-digit code from your authenticator app.");
    setBusy(true);
    setError(null);
    const supabase = createClient();
    const { error: verifyError } = await supabase.auth.mfa.challengeAndVerify({ factorId: mode.factorId, code: code.trim() });
    setBusy(false);
    if (verifyError) return setError("That code is not valid. Check the time on your phone and try again.");
    router.replace(next);
    router.refresh();
  }

  return (
    <form onSubmit={submit} className="space-y-4" noValidate>
      {error ? <Alert tone="danger">{error}</Alert> : null}
      {mode.kind === "enroll" ? (
        <div className="space-y-3">
          <p className="text-sm">Scan this QR code with an authenticator app (Google Authenticator, Authy, 1Password), then enter the 6-digit code.</p>
          {/* QR is an SVG data URI generated by Supabase */}
          {/* eslint-disable-next-line @next/next/no-img-element */}
          <img src={mode.qr} alt="Two-factor QR code" className="mx-auto h-44 w-44 rounded border bg-white p-2" />
          <p className="break-all text-center text-xs text-muted-foreground">
            Cannot scan? Enter this key: <code className="select-all">{mode.secret}</code>
          </p>
        </div>
      ) : null}
      {mode.kind === "verify" ? <p className="text-sm">Enter the 6-digit code from your authenticator app.</p> : null}
      <Field label="6-digit code" htmlFor="code">
        <Input id="code" inputMode="numeric" autoComplete="one-time-code" maxLength={6} value={code} onChange={(e) => setCode(e.target.value.replace(/\D/g, ""))} autoFocus />
      </Field>
      <Button type="submit" size="lg" className="w-full" disabled={busy || mode.kind === "loading"}>
        {busy ? "Checking..." : mode.kind === "enroll" ? "Turn on and continue" : "Verify"}
      </Button>
    </form>
  );
}
